#!/usr/bin/env python3
"""Writes unicode.bend, the character classes text.bend measures with.

    python3 tools/gen_unicode.py <dir> > unicode.bend

<dir> holds these files of the Unicode Character Database, version 18.0.0,
from https://www.unicode.org/Public/18.0.0/ucd/:

    EastAsianWidth.txt
    extracted/DerivedGeneralCategory.txt   (as DerivedGeneralCategory.txt)
    DerivedCoreProperties.txt
    emoji/emoji-data.txt                   (as emoji-data.txt)
    PropList.txt

Each code point gets a set of flags (below). Runs of code points with the
same flags become intervals, and Uni.flags is a balanced tree of
comparisons over the interval starts, one def per node.
"""
import os, re, sys

VERSION = "18.0.0"
FLAGS = [
  ("ZERO", "no width of its own: Cc, Mn, Me, Cf (but the prepended concatenation marks), Default_Ignorable_Code_Point"),
  ("WIDE", "East_Asian_Width W or F"),
  ("EMOJI", "Emoji"),
  ("EPRES", "Emoji_Presentation, in the BMP"),
  ("PICT", "Extended_Pictographic"),
  ("EMOD", "Emoji_Modifier"),
  ("EMODBASE", "Emoji_Modifier_Base"),
  ("RI", "Regional_Indicator"),
  ("HANGUL", "a Hangul syllable or a leading or vowel jamo: what a vowel or trailing jamo joins"),
  ("HVT", "a Hangul vowel or trailing jamo"),
]
BIT = {n: 1 << i for i, (n, _) in enumerate(FLAGS)}
PREPENDED = {0x600, 0x601, 0x602, 0x603, 0x604, 0x605, 0x6DD, 0x890, 0x891, 0x8E2, 0x110BD, 0x110CD}
# Hangul_Syllable_Type, stable since Unicode 5.2: L, V, T jamo and the
# precomposed syllables (LV and LVT)
HANGUL_L = [(0x1100, 0x115F), (0xA960, 0xA97C)]
HANGUL_V = [(0x1160, 0x11A7), (0xD7B0, 0xD7C6)]
HANGUL_T = [(0x11A8, 0x11FF), (0xD7CB, 0xD7FB)]
HANGUL_SYL = [(0xAC00, 0xD7A3)]

LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([A-Za-z_]+)")

def ranges(path, want):
  out = []
  for line in open(path, encoding="utf-8"):
    m = LINE.match(line)
    if m and m.group(3) in want:
      a = int(m.group(1), 16)
      out.append((a, int(m.group(2), 16) if m.group(2) else a))
  return out

def main(d):
  f = lambda n: os.path.join(d, n)
  for n in ["EastAsianWidth.txt", "DerivedGeneralCategory.txt", "DerivedCoreProperties.txt", "emoji-data.txt", "PropList.txt"]:
    head = open(f(n), encoding="utf-8").read(400)
    assert VERSION in head, n + " is not Unicode " + VERSION
  flags = {}
  def mark(rs, name, keep=lambda c: True):
    for a, b in rs:
      for c in range(a, b + 1):
        if keep(c):
          flags[c] = flags.get(c, 0) | BIT[name]
  mark(ranges(f("DerivedGeneralCategory.txt"), {"Cc", "Mn", "Me", "Cf"}), "ZERO", lambda c: c not in PREPENDED)
  mark(ranges(f("DerivedCoreProperties.txt"), {"Default_Ignorable_Code_Point"}), "ZERO")
  mark(ranges(f("EastAsianWidth.txt"), {"W", "F"}), "WIDE")
  mark(ranges(f("emoji-data.txt"), {"Emoji"}), "EMOJI")
  mark(ranges(f("emoji-data.txt"), {"Emoji_Presentation"}), "EPRES", lambda c: c <= 0xFFFF)
  mark(ranges(f("emoji-data.txt"), {"Extended_Pictographic"}), "PICT")
  mark(ranges(f("emoji-data.txt"), {"Emoji_Modifier"}), "EMOD")
  mark(ranges(f("emoji-data.txt"), {"Emoji_Modifier_Base"}), "EMODBASE")
  mark(ranges(f("PropList.txt"), {"Regional_Indicator"}), "RI")
  mark(HANGUL_L + HANGUL_V + HANGUL_SYL, "HANGUL")
  mark(HANGUL_V + HANGUL_T, "HVT")

  # intervals: (start, flags), each running to the next start
  iv = []
  prev = None
  for c in range(0x110000):
    v = flags.get(c, 0)
    if v != prev:
      iv.append((c, v))
      prev = v

  out = []
  w = out.append
  w("# unicode.bend: the character classes text.bend measures with, from the")
  w("# Unicode Character Database %s. Generated by tools/gen_unicode.py; do" % VERSION)
  w("# not edit. Uni.flags(c) is the set of these flags for code point c:")
  w("#")
  for name, why in FLAGS:
    w("#   %-9s %6d  %s" % (name, BIT[name], why))
  w("#")
  w("# %d intervals, a balanced tree of comparisons, one def per node." % len(iv))
  w("")
  w("import Base")
  w("")
  for name, _ in FLAGS:
    w("def Uni.%s() -> U32:" % name.lower())
    w("  %d" % BIT[name])
    w("")
  ids = [0]
  # emit the subtree over iv[lo:hi]; answers the expression its parent uses
  def tree(lo, hi):
    if hi - lo == 1:
      return str(iv[lo][1]), None
    m = (lo + hi) // 2
    le, lp = tree(lo, m)
    re_, rp = tree(m, hi)
    ids[0] += 1
    name = "Uni.t%d" % ids[0]
    w("def %s(+c: U32, lt: Bool) -> U32:" % name)
    w("  match lt:")
    w("    case True{}:")
    w("      %s" % (le if lp is None else "%s(c, U32.is_lt(c, %d))" % (le, lp)))
    w("    case False{}:")
    w("      %s" % (re_ if rp is None else "%s(c, U32.is_lt(c, %d))" % (re_, rp)))
    w("")
    return name, iv[m][0]
  root, pivot = tree(0, len(iv))
  w("def Uni.flags(+c: U32) -> U32:")
  w("  %s(c, U32.is_lt(c, %d))" % (root, pivot))
  w("")
  w("def Uni.has(+c: U32, f: U32) -> Bool:")
  w("  U32.is_ne(U32.and(Uni.flags(c), f), 0)")
  sys.stdout.write("\n".join(out) + "\n")

if __name__ == "__main__":
  main(sys.argv[1])
